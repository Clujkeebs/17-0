// Merges /tmp/strands-part-*.json into src/lib/minigames/puzzles/strands-boards.ts.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const boards = readdirSync('/tmp').filter((f) => /^strands-part-\d+\.json$/.test(f)).sort().flatMap((f) => JSON.parse(readFileSync(`/tmp/${f}`, 'utf8')));
const line = (b) => `  { theme: ${JSON.stringify(b.theme)}, letters: ${JSON.stringify(b.letters)}, words: [${b.words.map(([w, c]) => `[${JSON.stringify(w)}, [${c.join(',')}]]`).join(', ')}] },`;
writeFileSync('src/lib/minigames/puzzles/strands-boards.ts', `// GENERATED by scripts/strands-build.ts and scripts/strands-merge.mjs. Do not edit by hand.
// Each board: a theme, 48 letters (6 columns by 8 rows, row by row) and its words with the squares each one runs
// through, the spangram first. Every word can be spelled along exactly one path of the board (tests/unit/puzzles.test.ts).
export interface StrandsBoard { theme: string; letters: string; words: [string, number[]][] }
export const BOARDS: StrandsBoard[] = [
${boards.map(line).join('\n')}
];
`);
console.log(boards.length, 'boards');
